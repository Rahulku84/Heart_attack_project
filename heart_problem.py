    temporary_data = heart_df[["HeartAttackFlag", column]].copy()  # Select the outcome and current condition.
    temporary_data["ConditionFlag"] = temporary_data[column].str.casefold().map({"yes": 1, "no": 0})  # Encode explicit Yes and No responses.
    temporary_data = temporary_data.dropna(subset=["ConditionFlag"])  # Exclude unknown condition responses for this comparison.

